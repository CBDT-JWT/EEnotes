#!/usr/bin/env python3
"""Copy the public navigation and visual tokens from the homepage checkout."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://www.weitao-jiang.cn"


def sync(homepage):
    skin = (homepage / "static/css/ui-system.css").read_text(encoding="utf-8")
    root = re.search(r":root\s*\{(.*?)\n\}", skin, re.S)
    tokens = re.findall(r"^\s*(--ui-[\w-]+:\s*[^;]+;)", root[1], re.M) if root else []
    if not tokens:
        raise ValueError("Cannot find the homepage visual tokens")
    # The homepage applies its profile layout after the shared visual contract.
    # Include those overrides and the final navigation rules in the same order.
    profile = (homepage / "static/css/academic-home.css").read_text(encoding="utf-8")
    profile_root = re.search(r"html\.academic-document\s*\{(.*?)\}", profile, re.S)
    wide_root = re.search(r"(@media\s*\(min-width:\s*1180px\))\s*\{\s*html\.academic-document\s*\{(.*?)\}", profile, re.S)
    nav_rules = re.search(r"/\* A single navigation.*?\*/(.*?)(?=/\* Page heading)", skin, re.S)
    mobile_nav_rules = re.search(r"@media\s*\(max-width:\s*820px\)\s*\{.*?\n\}", skin, re.S)
    if not all((profile_root, wide_root, nav_rules, mobile_nav_rules)):
        raise ValueError("Cannot find the homepage layout and navigation overrides")
    tokens_css = "/* Generated by scripts/sync_homepage_ui.py. */\n:root {\n" + "\n".join("  " + token for token in tokens) + "\n}\n"
    tokens_css += ":root {" + profile_root[1] + "}\n"
    tokens_css += wide_root[1] + " {\n  :root {" + wide_root[2] + "}\n}\n"
    tokens_css += nav_rules[1].strip() + "\n"
    tokens_css += mobile_nav_rules[0] + "\n"
    navigation = (homepage / "static/js/global.js").read_text(encoding="utf-8")
    header = re.search(r'<header class="landing-nav".*?</header>', navigation, re.S)
    if not header:
        raise ValueError("Cannot find the homepage public navigation")
    header = header[0].replace('<header ', '<div ', 1).replace('</header>', '</div>')
    header = re.sub(r'href="(/[^\"]*)"', lambda match: f'href="{ORIGIN}{match[1]}"', header)
    header = header.replace('data-nav-route="notes"', 'data-nav-route="notes" aria-current="page"')
    outputs = {
        "docs/stylesheets/homepage-tokens.css": tokens_css,
        "docs/stylesheets/public-header.css": (homepage / "static/css/public-header.css").read_text(encoding="utf-8"),
        "overrides/partials/site-nav.html": "{# Generated by scripts/sync_homepage_ui.py. #}\n" + header + "\n",
    }
    for relative, content in outputs.items():
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
        print(relative)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--homepage-dir", type=Path, default=ROOT.parent / "homepage")
    sync(parser.parse_args().homepage_dir.resolve())
