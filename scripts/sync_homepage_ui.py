#!/usr/bin/env python3
"""Copy the public navigation and visual tokens from the homepage checkout."""
import argparse
import re
import shutil
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://www.weitao-jiang.cn"
ASSET_VERSION = "20261022-unified-2"


def sync(homepage):
    skin = (homepage / "static/css/site-layout.css").read_text(encoding="utf-8")
    if not all(token in skin for token in ("--ui-width:", "--ui-page-offset:", "--public-nav-gutter:")):
        raise ValueError("Cannot find the homepage visual tokens")
    navigation = (homepage / "static/js/global.js").read_text(encoding="utf-8")
    header = re.search(r'<header class="landing-nav".*?</header>', navigation, re.S)
    if not header:
        raise ValueError("Cannot find the homepage public navigation")
    header = header[0].replace('<header ', '<div ', 1).replace('</header>', '</div>')
    header = re.sub(r'href="(/[^\"]*)"', lambda match: f'href="{ORIGIN}{match[1]}"', header)
    header = header.replace('data-nav-route="notes"', 'data-nav-route="notes" aria-current="page"')
    outputs = {
        "docs/stylesheets/homepage-tokens.css": skin,
        "docs/stylesheets/public-header.css": (homepage / "static/css/public-header.css").read_text(encoding="utf-8"),
        "docs/stylesheets/homepage-typography.css": (homepage / "static/css/typography.css").read_text(encoding="utf-8"),
        "docs/stylesheets/editorial-fonts.css": (homepage / "static/css/editorial-fonts.css").read_text(encoding="utf-8"),
        "docs/stylesheets/site-theme.css": (homepage / "static/css/site-theme.css").read_text(encoding="utf-8"),
        "overrides/partials/site-nav.html": "{# Generated by scripts/sync_homepage_ui.py. #}\n" + header + "\n",
    }
    for relative, content in outputs.items():
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
        print(relative)

    # Relative ../fonts/ URLs work unchanged on the independently hosted notes.
    font_css = outputs["docs/stylesheets/editorial-fonts.css"]
    for url in re.findall(r'url\(\s*[\'"]?([^\'"\)\s]+)', font_css):
        parsed = urlsplit(url)
        if parsed.scheme or parsed.netloc:
            raise ValueError("Editorial fonts must be self-hosted")
        source = (homepage / "static/css" / parsed.path).resolve()
        if not source.is_relative_to((homepage / "static/fonts").resolve()):
            raise ValueError("Editorial font path is outside static/fonts")
        target = ROOT / "docs/fonts" / source.name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_bytes() != source.read_bytes():
            shutil.copy2(source, target)
        print(target.relative_to(ROOT))
    notices = [*sorted((homepage / "static/fonts").glob("OFL*.txt")), homepage / "static/fonts/README.md"]
    for source in notices:
        target = ROOT / "docs/fonts" / source.name
        if not target.exists() or target.read_bytes() != source.read_bytes():
            shutil.copy2(source, target)

    widget = re.search(r"assistant\.src\s*=\s*['\"](/static/js/chatjwt\.js\?[^'\"]+)['\"]", navigation)
    if not widget:
        raise ValueError("Cannot find the main site's chatJWT asset version")
    widget_url = ORIGIN + widget[1]
    config_path = ROOT / "mkdocs.yml"
    config = config_path.read_text(encoding="utf-8")
    styles = [
        "css/neoteroi-mkdocs.css",
        f"stylesheets/public-header.css?v={ASSET_VERSION}",
        f"stylesheets/homepage-tokens.css?v={ASSET_VERSION}",
        "https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/katex.min.css",
        f"stylesheets/homepage-typography.css?v={ASSET_VERSION}",
        f"stylesheets/editorial-fonts.css?v={ASSET_VERSION}",
        f"stylesheets/site-theme.css?v={ASSET_VERSION}",
        f"stylesheets/homepage-palette.css?v={ASSET_VERSION}",
    ]
    config, count = re.subn(r'(?ms)^extra_css:\n.*?(?=^nav:)',
                            "extra_css:\n" + "".join(f"- {style}\n" for style in styles) + "\n\n", config)
    if count != 1:
        raise ValueError("Cannot find the notes stylesheet configuration")
    config = re.sub(r'https://www\.weitao-jiang\.cn/static/js/chatjwt\.js\?[^\s]+', widget_url, config)
    config = re.sub(r'(?m)^- javascripts/site-navigation\.js(?:\?[^\s]+)?$',
                    f'- javascripts/site-navigation.js?v={ASSET_VERSION}', config)
    config_path.write_text(config, encoding="utf-8")
    build_path = ROOT / "scripts/chatjwt_build.py"
    build_source = build_path.read_text(encoding="utf-8")
    build_source, count = re.subn(r"(?m)^SCRIPT_URL = '[^']+'$", f"SCRIPT_URL = '{widget_url}'", build_source)
    if count != 1:
        raise ValueError("Cannot find the notes companion build asset version")
    build_path.write_text(build_source, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--homepage-dir", type=Path, default=ROOT.parent / "homepage")
    sync(parser.parse_args().homepage_dir.resolve())
